/* Scriptdesk — Discover: questions that help you find out who your characters are and what your places mean. */
(function () {
  'use strict';
  const SD = (window.SD = window.SD || {});
  const Q = (cat, list) => list.map((q) => ({ cat, q }));

  SD.DISCOVER = {
    character: [
      ...Q('Daily life', [
        'What do they do in the first ten minutes after waking up?',
        'What is in their pockets, bag or glovebox right now?',
        'What do they eat when no one is watching?',
        'Which chore do they always put off?',
        'How do they spend a free Sunday afternoon?',
        'What is the most worn-out thing they own, and why do they keep it?',
        'What would their neighbours say about them?',
        'What do they spend too much money on?',
        'What is on their bedside table?',
        'What time do they go to bed, and what keeps them awake?',
        'Which song do they know every word of?',
        'How do they behave when they are bored?',
      ]),
      ...Q('Relationships', [
        'Who was the last person they lied to, and why?',
        'Who do they call first with good news? With bad news?',
        'Who do they owe something to?',
        'Who would they never forgive?',
        'Who knows them better than they would like?',
        'What do they want from the person they spend the most time with?',
        'Who did they love first, and how did it end?',
        'Which friend have they lost touch with, and whose fault was it?',
        'What do their parents (or the people who raised them) still not know about them?',
        'Who do they compare themselves to?',
        'What does everyone around them get wrong about them?',
        'What do they do when someone cries in front of them?',
      ]),
      ...Q('The past', [
        'What is their earliest memory?',
        'What is the worst thing that ever happened to them?',
        'What is the best day of their life so far?',
        'What did they want to be when they were ten?',
        'What were they punished for as a child?',
        'When did they last feel truly safe?',
        'What mistake do they replay in their head?',
        'Which decision split their life into "before" and "after"?',
        'What did they lose that they never got back?',
        'Which rule from home do they still follow without thinking?',
        'What story do they tell about themselves at parties — and what is the true version?',
      ]),
      ...Q('Fears & desires', [
        'What are they most afraid people will find out?',
        'What would they do with a year off and enough money?',
        'What would make them walk away from everything?',
        'What do they want so badly they are embarrassed by it?',
        'What are they afraid of becoming?',
        'What would they risk their life for? Their reputation?',
        'What do they pretend not to want?',
        'When were they last jealous, and of whom?',
        'What would a perfect ordinary day look like to them?',
        'What do they think will happen to them when they are old?',
        'What is the one thing they would change about themselves?',
      ]),
      ...Q('Under pressure', [
        'What do they do first when something goes wrong?',
        'When cornered, do they fight, run, freeze or charm?',
        'What is the first thing they would grab if their home was on fire?',
        'How do they apologise — or do they?',
        'What do they say when they are lying? What do their hands do?',
        'What is the line they would never cross — and what would push them across it?',
        'Who would they sacrifice to save themselves? Who would they sacrifice themselves for?',
        'How do they behave when they are winning?',
        'What do they do when they are humiliated in public?',
        'What does it take to make them laugh in a bad moment?',
      ]),
      ...Q('Beliefs & voice', [
        'What do they believe that most people around them do not?',
        'What is a phrase they say too often?',
        'What would they never say out loud?',
        'Do they believe people can change?',
        'What do they think they deserve?',
        'What makes them angry on behalf of someone else?',
        'Which opinion would they defend even if everyone left the room?',
        'How do they talk to someone they want something from?',
        'How do they talk to children? To animals? To people they think are beneath them?',
        'What do they pray for, wish for, or tell themselves at night?',
      ]),
      ...Q('In this story', [
        'What do they want in the first scene, in one sentence?',
        'What would happen to them if the story never started?',
        'Why does this story have to happen to them, and not someone else?',
        'Where are they lying to themselves at the start?',
        'Which scene would they hate to be in?',
        'What do they want from the antagonist — or from the protagonist?',
        'What do they know that the audience does not, and for how long?',
        'In the last scene, what do they have that they did not have at the start? What did it cost?',
        'Which choice in the story could they only make after everything that happened?',
        'If they told the story, where would they start it?',
      ]),
    ],
    location: [
      ...Q('First look', [
        'What is the first thing you notice when you walk in?',
        'What sound never stops here?',
        'What does it smell like after rain? At night?',
        'Where is the light coming from, and what does it hide?',
        'What is broken here and never repaired?',
        'What is out of place?',
      ]),
      ...Q('People', [
        'Who comes here every day? Who has never been allowed in?',
        'Who cleans it, and what do they know about the people here?',
        'Who feels at home here — and who feels watched?',
        'What would a stranger misunderstand about this place?',
        'What rule does everyone here follow without saying it?',
      ]),
      ...Q('History', [
        'What happened here before the story starts?',
        'What was this place built for, and what is it used for now?',
        'What would it have looked like twenty years ago?',
        'Who has left something behind here?',
        'Which memory of this place does a character avoid?',
      ]),
      ...Q('In this story', [
        'Why does this scene have to happen here, and not somewhere else?',
        'What can a character do here that they cannot do anywhere else?',
        'How is the place different the last time we see it?',
        'What would happen if the place were taken away?',
        'Where in this place would someone hide something?',
        'Which part of it never appears on screen, but everyone knows is there?',
      ]),
    ],
    item: [
      ...Q('The object', [
        'Who owned it before?',
        'What does it say about the person who carries it?',
        'What would it mean if it were lost? If it were broken?',
        'Who else wants it, and why?',
        'Where is it kept, and who knows where?',
        'When does the audience first see it — and do they notice it?',
        'What changes about it by the end?',
      ]),
    ],
  };
  SD.discoverKind = (category) => (category === 'character' ? 'character' : category === 'location' ? 'location' : 'item');
})();
